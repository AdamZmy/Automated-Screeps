#!/usr/bin/env node
'use strict';
// Offline only: preserve acknowledged layouts across future summary-only API
// snapshots. Never fetch data or deploy from this generator.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const root=path.resolve(__dirname,'..');
const args=process.argv.slice(2);
function option(name,fallback){const at=args.indexOf(name);if(at<0)return fallback;if(!args[at+1]||args[at+1].startsWith('--'))throw Error('Missing value for '+name);return path.resolve(args[at+1]);}
const input=option('--snapshot',path.join(root,'state/room-plans-before.json'));
const output=option('--output',path.join(root,'plans.js'));
const rooms=JSON.parse(fs.readFileSync(input,'utf8'));
const records={};
if(fs.existsSync(output)){
    const previous=require(output);
    if(typeof previous.list!=='function'||typeof previous.load!=='function')throw Error('Existing archive cannot be safely merged');
    for(const [room,ids] of Object.entries(previous.list())){
        records[room]={};
        for(const id of ids){const plan=previous.load(room,id);if(!plan)throw Error('Missing existing archive '+room+' / '+id);records[room][id]=JSON.stringify(plan);}
    }
}
let added=0,summaries=0;
for(const [room,memory] of Object.entries(rooms)){
    const plan=memory&&memory.plan;if(!plan)continue;
    if(!Array.isArray(plan.structures)){
        if(plan.archiveId&&!(records[room]&&records[room][plan.archiveId]))throw Error('Snapshot references an unavailable archive: '+room+' / '+plan.archiveId);
        summaries++;continue;
    }
    if(!Number.isInteger(plan.version)||!Number.isFinite(plan.created)||plan.structures.some(s=>!s||typeof s.type!=='string'||!Number.isInteger(s.x)||!Number.isInteger(s.y)))throw Error('Invalid executable plan for '+room);
    const data=JSON.stringify(plan),id=crypto.createHash('sha256').update(room+'\n'+data).digest('hex');
    records[room]=records[room]||{};
    if(!records[room][id])added++;
    records[room][id]=data;
}
if(!Object.keys(records).length)throw Error('No full layouts or existing archives to preserve');
const generated="'use strict';\n// Generated by tools/build-plan-archive.cjs from acknowledged API snapshots.\n// JSON strings are parsed only when one room becomes an execution target.\n"+
    'const records='+JSON.stringify(records,null,2)+';\n'+
    `module.exports={
    has(name){return Object.prototype.hasOwnProperty.call(records,name);},
    identify(name,plan){
        const versions=records[name];if(!versions)return null;
        const data=JSON.stringify(plan);
        return Object.keys(versions).find(id=>versions[id]===data)||null;
    },
    load(name,id){
        const versions=records[name],data=versions&&versions[id];
        return typeof data==='string'?JSON.parse(data):null;
    },
    list(){return Object.fromEntries(Object.entries(records).map(([name,versions])=>[name,Object.keys(versions)]));}
};
`;
fs.mkdirSync(path.dirname(output),{recursive:true});
const temporary=output+'.tmp-'+process.pid;
fs.writeFileSync(temporary,generated);fs.renameSync(temporary,output);
console.log(JSON.stringify({rooms:Object.keys(records).length,versions:Object.values(records).reduce((n,v)=>n+Object.keys(v).length,0),added,preservedSummaries:summaries,bytes:Buffer.byteLength(generated),output}));
