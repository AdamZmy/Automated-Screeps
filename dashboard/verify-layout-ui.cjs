/* Read-only layout UI verification. No network requests or game credentials. */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const { JSDOM } = require('jsdom');
const root = __dirname;
const html = fs.readFileSync(path.join(root, 'public/index.html'), 'utf8');
const script = fs.readFileSync(path.join(root, 'public/layout.js'), 'utf8');
const css = fs.readFileSync(path.join(root, 'public/layout.css'), 'utf8');
const payload = JSON.parse(fs.readFileSync(path.join(root, 'public/data/room-layouts.json'), 'utf8'));
const context = { module: { exports: {} }, Intl, Map, Number, Date };
vm.runInNewContext(script, context);
const { normalizeLayouts } = context.module.exports;
const normalized = normalizeLayouts(payload);
const primary = normalized.rooms[normalized.primaryRoom];
assert.equal(primary.terrain.length, 2500);
assert.equal(primary.plan.buildings.length, payload.rooms[normalized.primaryRoom].plan.buildings.length);
const undated = structuredClone(payload);
undated.rooms[normalized.primaryRoom].snapshot = { status: 'unavailable' };
assert.ok(normalizeLayouts(undated).rooms[normalized.primaryRoom].plan.buildings.every(item => item.status === 'unknown'), 'missing state capture cannot assert built or unbuilt');
const invalid = structuredClone(payload);
invalid.rooms[normalized.primaryRoom].terrain = '0'.repeat(2499);
assert.equal(Object.keys(normalizeLayouts(invalid).rooms).length, 0, 'invalid terrain must never render fabricated plain cells');
const fixtures = [];
const flush = () => new Promise(resolve => setImmediate(resolve));
async function create(body, ok = true, earlyTelemetry) {
  const dom = new JSDOM(html, { url: 'http://localhost', runScripts: 'outside-only', pretendToBeVisual: true });
  fixtures.push(dom);
  const calls = [];
  dom.window.fetch = async (url, options) => { calls.push({ url, options }); await flush(); return { ok, status: ok ? 200 : 500, json: async () => body }; };
  dom.window.AbortController = AbortController;
  dom.window.eval(script);
  if (earlyTelemetry) dom.window.document.dispatchEvent(new dom.window.CustomEvent('screeps:telemetry', { detail: earlyTelemetry }));
  await flush(); await flush();
  return { dom, d: dom.window.document, calls };
}
(async () => {
  const telemetry = { tick: primary.snapshot.tick + 150, rooms: { [primary.name]: { rcl: 4 } } };
  const { dom, d, calls } = await create(payload, true, telemetry);
  const click = selector => { const element = d.querySelector(selector); assert.ok(element, `missing ${selector}`); element.click(); };
  const change = (id, value) => { const element = d.getElementById(id); if (typeof value === 'boolean') element.checked = value; else element.value = value; element.dispatchEvent(new dom.window.Event('change')); };
  assert.equal(calls.length, 1);
  assert.equal(calls[0].url, '/data/room-layouts.json');
  assert.equal(calls[0].options.credentials, 'omit');
  assert.equal(d.getElementById('layout-content').hidden, false);
  assert.equal(d.querySelectorAll('[data-layout-rcl]').length, 8);
  assert.equal(d.querySelector('[data-layout-rcl="8"]').getAttribute('aria-pressed'), 'true');
  assert.equal(d.getElementById('layout-current-rcl').textContent, '当前 RCL 4', 'telemetry arriving before static data must be retained');
  assert.equal(d.querySelectorAll('#layout-map .layout-building').length, primary.plan.buildings.length);
  assert.equal(d.querySelectorAll('[data-layout-locate]').length, primary.plan.buildings.length, 'every planned building must have a locatable list entry');
  assert.equal(d.querySelectorAll('#layout-map [data-cell]').length, 2500);
  assert.equal(d.querySelectorAll('.layout-natural-source').length, primary.objects.sources.length);
  assert.equal(d.querySelectorAll('.layout-natural-controller').length, primary.objects.controller ? 1 : 0);
  assert.equal(d.querySelectorAll('.layout-natural-mineral').length, primary.objects.mineral ? 1 : 0);
  assert.equal(d.querySelectorAll('#layout-map .layout-rcl-label').length, primary.plan.buildings.filter(item => !['road', 'rampart'].includes(item.type)).length, 'road and rampart levels must not cover the map with text');
  assert.match(d.getElementById('layout-snapshot-time').textContent, new RegExp(primary.snapshot.tick.toLocaleString('en-US')));
  const initialSnapshotText = d.getElementById('layout-snapshot-time').textContent;
  const initialBuiltCount = d.querySelectorAll('#layout-map .layout-status-built').length;
  // Export the complete actual map; no fixture data enters public/.
  fs.mkdirSync(path.join(root, 'test-output'), { recursive: true });
  const svg = d.querySelector('#layout-map > svg.layout-map-svg').cloneNode(true);
  svg.setAttribute('width', '1080'); svg.setAttribute('height', '1080');
  const styles = d.createElementNS('http://www.w3.org/2000/svg', 'style'); styles.textContent = css; svg.insertBefore(styles, svg.firstChild);
  fs.writeFileSync(path.join(root, 'test-output/layout-map.svg'), new dom.window.XMLSerializer().serializeToString(svg));
  for (let rcl = 1; rcl <= 8; rcl++) {
    click(`[data-layout-rcl="${rcl}"]`);
    assert.equal(d.querySelectorAll('#layout-map .layout-building').length, primary.plan.buildings.filter(item => item.rcl <= rcl).length);
    click('[data-layout-mode="new"]');
    assert.equal(d.querySelectorAll('#layout-map .layout-building').length, primary.plan.buildings.filter(item => item.rcl === rcl).length);
    click('[data-layout-mode="cumulative"]');
  }
  change('layout-roads', false);
  assert.equal(d.querySelectorAll('#layout-map [data-building-type="road"]').length, 0);
  assert.equal(d.querySelectorAll('#layout-map .layout-building').length, primary.plan.buildings.filter(item => item.type !== 'road').length);
  change('layout-protection', false);
  assert.equal(d.querySelectorAll('#layout-map [data-building-type="rampart"]').length, 0);
  change('layout-type', 'road');
  assert.equal(d.querySelectorAll('#layout-map .layout-building').length, 0);
  assert.match(d.getElementById('layout-building-list').textContent, /没有建筑/);
  change('layout-roads', true);
  assert.equal(d.querySelectorAll('#layout-map .layout-building').length, primary.plan.buildings.filter(item => item.type === 'road').length);
  change('layout-type', 'all'); change('layout-protection', true);
  // A selected cell always lists all stacked plans, including hidden/future layers.
  const stacked = primary.plan.buildings.find(item => primary.plan.buildings.filter(other => other.x === item.x && other.y === item.y).length > 1);
  assert.ok(stacked, 'real plan needs at least one stacked cell for this coverage');
  click('[data-layout-rcl="1"]'); change('layout-protection', false);
  d.querySelector(`#layout-map [data-cell="${stacked.x},${stacked.y}"]`).dispatchEvent(new dom.window.MouseEvent('click', { bubbles: true }));
  assert.equal(d.querySelectorAll('.layout-cell-building').length, primary.plan.buildings.filter(item => item.x === stacked.x && item.y === stacked.y).length);
  assert.match(d.getElementById('layout-cell-detail').textContent, /当前筛选外/);
  assert.match(d.getElementById('layout-cell-detail').textContent, /最早 RCL/);
  assert.equal(d.getElementById('layout-cell-coordinate').textContent, `(${stacked.x}, ${stacked.y})`);
  click('[data-layout-rcl="8"]'); change('layout-protection', true);
  const last = primary.plan.buildings.at(-1);
  const locate = [...d.querySelectorAll('[data-layout-locate]')].find(button => button.dataset.layoutLocate === last.id);
  locate.click();
  assert.equal(d.getElementById('layout-map-selection').getAttribute('x'), String(last.x));
  assert.equal(d.getElementById('layout-map-selection').getAttribute('y'), String(last.y));
  assert.equal(locate.getAttribute('aria-pressed'), 'true');
  d.querySelector('.layout-map-svg').dispatchEvent(new dom.window.KeyboardEvent('keydown', { key: 'ArrowRight', bubbles: true }));
  assert.equal(d.getElementById('layout-map-selection').getAttribute('x'), String(Math.min(49, last.x + 1)));
  click('#layout-core'); assert.equal(d.getElementById('layout-zoom-label').textContent, '250%');
  click('#layout-zoom-in'); assert.equal(d.getElementById('layout-zoom-label').textContent, '300%');
  assert.equal(d.getElementById('layout-zoom-in').disabled, true);
  click('#layout-fit'); assert.equal(d.getElementById('layout-zoom-label').textContent, '100%');
  assert.equal(d.getElementById('layout-zoom-out').disabled, true);
  d.dispatchEvent(new dom.window.CustomEvent('screeps:telemetry', { detail: { stale: true, tick: primary.snapshot.tick + 1000, rooms: { [primary.name]: { rcl: 6 } } } }));
  assert.equal(d.getElementById('layout-current-rcl').textContent, '当前 RCL 6');
  assert.match(d.getElementById('layout-telemetry-time').textContent, /最近遥测（已过期）/);
  assert.equal(d.getElementById('layout-snapshot-time').textContent, initialSnapshotText);
  assert.equal(d.querySelectorAll('#layout-map .layout-status-built').length, initialBuiltCount, 'new telemetry must not mutate captured building state');
  assert.equal(calls.length, 1, 'layout interactions and telemetry must not issue extra fetches');
  assert.doesNotMatch(d.getElementById('layout').textContent, /NaN|Infinity|undefined/);
  assert.match(css, /@media\(max-width:700px\)/);
  assert.match(css, /overflow:auto/);
  // Independent room selection, defensive terrain handling, and untrusted text.
  const malicious = structuredClone(payload);
  malicious.rooms.W22N26 = structuredClone(malicious.rooms[primary.name]);
  malicious.rooms.W22N26.currentRcl = 1;
  malicious.rooms.W22N26.plan.buildings = [{ type: 'spawn', x: 20, y: 20, rcl: 1, status: 'site', tag: '<img src=x onerror="window.attacked=true">', conditions: ['<script>alert(1)</script>'] }];
  malicious.rooms.W22N26.plan.notes = ['<img src=x onerror="window.attacked=true">'];
  const second = await create(malicious);
  second.d.getElementById('layout-room').value = 'W22N26'; second.d.getElementById('layout-room').dispatchEvent(new second.dom.window.Event('change'));
  assert.equal(second.d.getElementById('layout-current-rcl').textContent, '当前 RCL 1');
  assert.equal(second.d.querySelectorAll('#layout-map .layout-building').length, 1);
  assert.equal(second.d.querySelectorAll('#layout img, #layout script').length, 0);
  assert.match(second.d.getElementById('layout-cell-detail').textContent, /<img/);
  assert.equal(second.d.querySelectorAll('#layout-map .layout-status-site').length, 1);
  const failure = await create({}, false);
  assert.equal(failure.d.getElementById('layout-content').hidden, true);
  assert.match(failure.d.getElementById('layout-notice').textContent, /暂不可用/);
  assert.ok(failure.d.getElementById('utilization-value'), 'layout failures leave energy UI available');
  console.log(`Layout UI verified: ${primary.plan.buildings.length} real plans, all 8 RCL cumulative/new sets, terrain and objects, filters, stacked cells, list location, keyboard, zoom, dated building state, early/stale telemetry, multiple rooms, safe text, graceful failure, one public fetch. SVG: test-output/layout-map.svg`);
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(() => fixtures.forEach(dom => dom.window.close()));
